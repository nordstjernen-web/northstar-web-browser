#!/usr/bin/env python3
# embed-pdfjs-fonts.py: generate a C table of PDF.js standard font files (name, bytes, length) for src/pdf.c.
import os
import sys


def main(argv):
    if len(argv) < 3:
        sys.stderr.write("usage: embed-pdfjs-fonts.py OUT.h FONT...\n")
        return 2
    out, fonts = argv[1], argv[2:]
    lines = ["/* generated by embed-pdfjs-fonts.py — do not edit */",
             "typedef struct { const char *name; const unsigned char *data;"
             " unsigned len; } ns_pdfjs_font;"]
    for i, path in enumerate(fonts):
        with open(path, "rb") as f:
            data = f.read()
        body = ",\n".join("    " + ", ".join("0x%02x" % b for b in data[j:j + 16])
                          for j in range(0, len(data), 16))
        lines.append("static const unsigned char ns_pdfjs_font_%d[] = {\n%s\n};"
                     % (i, body))
    lines.append("static const ns_pdfjs_font ns_pdfjs_fonts[] = {")
    for i, path in enumerate(fonts):
        name = os.path.basename(path)
        if not all(c.isalnum() or c in "-_." for c in name):
            sys.stderr.write("unexpected font file name: %s\n" % name)
            return 1
        lines.append('    { "%s", ns_pdfjs_font_%d, sizeof ns_pdfjs_font_%d },'
                     % (name, i, i))
    lines.append("};")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
